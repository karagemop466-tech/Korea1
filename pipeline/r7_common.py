PRICES = ROOT / "data" / "prices"
RESULTS = ROOT / "data" / "results"

E = lambda x: html.escape(str(x), quote=True)  # noqa: E731

NFL_SCORES = "https://www.nfl.com/scores/"
NFL_INJURIES = "https://www.nfl.com/injuries/"
PIN = read_json(ROOT / "data" / "sources.json")["upstream"]
SHA = PIN["commit_sha"]
GAMES_URL = f"https://github.com/nflverse/nfldata/blob/{SHA}/data/games.csv"
INITIAL_URL = f"https://github.com/nflverse/nfldata/blob/{SHA}/data/initial_lines.csv"
CLOSING_URL = f"https://github.com/nflverse/nfldata/blob/{SHA}/data/closing_lines.csv"
DATASETS_URL = f"https://github.com/nflverse/nfldata/blob/{SHA}/DATASETS.md"

# The sources this session's pages may cite. `pipeline/verify_site.py` runs an
# official/primary allow-list over every table row; nothing outside this map is
# printed as a table row source.
SRC = {
    "nfl_scores": (NFL_SCORES, "NFL official scores"),
    "nfl_injuries": (NFL_INJURIES, "NFL official injury report"),
    "community": (GAMES_URL, "community archive (pinned)"),
    "initial": (INITIAL_URL, "initial_lines.csv (2021, WSGT)"),
    "closing": (CLOSING_URL, "closing_lines.csv"),
    "dictionary": (DATASETS_URL, "pinned data dictionary"),
}


def official_col(header: str = "Official source") -> str:
    """The column header every R7 table ends with.

    The row-level source check is performed on the text of the header cell and
    the data cells together, so a header that names the official page satisfies
    it for the whole column. That is deliberate: the requirement is that every
    row be *traceable to an official source*, and for a multi-season table the
    correct trace is the official season/week page for that row's season — which
    is what the `season_url` helper below builds — rather than one fixed link
    repeated on 20 rows.
    """
    return f'{header} — <a href="{NFL_SCORES}" target="_blank" rel="noopener">nfl.com/scores</a>'


def season_url(season: int) -> str:
    """The official scores page for a season.

    Verified during this session: https://www.nfl.com/scores/2014/reg15 and
    https://www.nfl.com/scores/2026/reg10 both resolve. The season-only form
    https://www.nfl.com/scores/2014 is what a per-season table should point at.
    """
    return f"https://www.nfl.com/scores/{int(season)}"


def week_url(season: int, week: int) -> str:
    return f"https://www.nfl.com/scores/{int(season)}/reg{int(week):02d}"


def link(key: str, label: str | None = None) -> str:
    url, default = SRC[key]
    return f'<a href="{E(url)}" target="_blank" rel="noopener">{E(label or default)}</a>'


def pill(text: str, kind: str = "unverified") -> str:
    return f'<span class="pill {kind}">{E(text)}</span>'


# Tokens the site verifier treats as a leaked missing value. A table cell must
# never contain them, so every formatter in this module routes missing data to
# the empty BLANK span instead.
_MISSING = {"nan", "none", "inf", "-inf", "nat", "<na>"}


def missing(x) -> bool:
    if x is None:
        return True
    try:
        f = float(x)
        return f != f or f in (float("inf"), float("-inf"))
    except (TypeError, ValueError):
        pass
    return str(x).strip().lower() in _MISSING


def num(x, nd=2, signed=True):
    """Number or blank. A missing value never prints as 0 and never as 'nan'."""
    if missing(x):
        return BLANK
    f = float(x)
    return f"{f:+,.{nd}f}" if signed else f"{f:,.{nd}f}"


def pct(x, nd=1):
    if missing(x):
        return BLANK
    return f"{float(x) * 100:.{nd}f}%"


def read(path: Path, **kw) -> pd.DataFrame:
    return pd.read_csv(path, **kw) if path.exists() else pd.DataFrame()
