"""T31 — render `decision-hub.html`: one canonical decision list for the whole project.

The site carries six suggestion registers and five question registers written by different
sessions on different branches. This page does not replace any of them: it lists them,
maps every one of their 166 rows onto 16 canonical decisions, and proves by construction
that nothing was dropped (the coverage table is generated by `build_hub.py`, which fails
the build if any row is unmapped or mapped twice).
"""
from __future__ import annotations

import csv
import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_hub import FALLBACK_LABEL, FALLBACK_URL  # noqa: E402
from render_site import OFFICIAL, ROOT, card, e, flag, kpi_grid, layout, src_link, table  # noqa: E402

RV = ROOT / "data" / "review"

REGISTER_NOTE = {
    "S": "arena/25460478-korea1",
    "DB": "arena/c0528572-korea1",
    "SR": "arena/774867ed-korea1",
    "SUG": "arena/d6b3fd34-korea1",
    "Q": "arena/25460478-korea1",
    "OQ": "arena/c0528572-korea1",
    "DQ": "arena/03f66e17-korea1",
    "QR": "arena/774867ed-korea1",
}


def read(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with open(path, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def dash(x: str) -> str:
    x = (x or "").strip()
    return e(x) if x else '<span class="blank">—</span>'


def pill(text: str, tone: str = "") -> str:
    return f'<span class="pill {tone}">{e(text)}</span>' if text else ""


def ref(label_key: str) -> str:
    url = OFFICIAL.get(label_key)
    return src_link(url, label_key) if url else e(label_key)


def build() -> str:
    decisions = read(RV / "hub_decisions.csv")
    mapping = read(RV / "hub_map.csv")
    coverage = read(RV / "hub_coverage.csv")
    summary = json.loads((RV / "hub_summary.json").read_text())
    body = []

    by_dec = defaultdict(list)
    for m in mapping:
        by_dec[m["canonical_id"]].append(m)

    # ---- cards ------------------------------------------------------------
    body.append(kpi_grid([
        card(str(len(decisions)), "Canonical decisions",
             "the whole review surface reduced to what you must actually choose"),
        card(str(len(mapping)), "Source rows mapped",
             f"{summary['register_rows_total']} register rows across "
             f"{len(coverage)} machine-readable registers"),
        card(f"{summary['register_rows_mapped']}/{summary['register_rows_total']}",
             "Coverage", "every register row is claimed by exactly one decision", "pos"),
        card("6 + 5", "Registers consolidated",
             "six suggestion registers, five question registers, written by six sessions"),
        card("2", "Decisions to take first",
             "DH-02 price provenance and DH-04 data freshness unblock the rest"),
        card("0", "Changes implemented here",
             "this hub only re-indexes what is already published", "pos"),
    ]))

    body.append(flag(
        "<strong>Why this page exists.</strong> Six agent sessions each wrote their own "
        "suggestion register and their own question register on their own branches, without "
        "being able to see each other's work. The site therefore carries <em>six</em> "
        "suggestion registers and <em>five</em> question registers covering the same ground, "
        "under four different id schemes (S, DB, S-nn, SUG / Q, OQ, DQ, Q-nn). Nothing on "
        "this page is new content: every one of the 166 rows below links back to the "
        "register it came from, so you can read the original wording before choosing.", "info"))

    # ---- register map -----------------------------------------------------
    rhdr = ["Register", "Ids", "Rows", "Published on", "Written by", "Verdict",
            "Reference most cited by its rows"]
    rtrs = []
    for c in coverage:
        code = c["register"]
        rtrs.append([
            f'<strong>{e(c["label"])}</strong>',
            f'<code>{e(code)}</code>',
            e(c["rows"]),
            f'<a href="{e(c["page"])}">{e(c["page"])}</a>',
            f'<code>{e(REGISTER_NOTE.get(code, "—"))}</code>',
            ("superseded by this hub for navigation; retained as the original wording"
             if c["rows"] else ""),
            src_link(c["reference_url"], c["reference_label"]),
        ])
    for label, page, note in summary.get("prose_registers", []):
        rtrs.append([f"<strong>{e(label)}</strong>", '<code>prose</code>',
                     '<span class="blank">—</span>', f'<a href="{e(page)}">{e(page)}</a>',
                     f'<code>{e(note.split(",")[0])}</code>',
                     "not a table, so not row-mapped",
                     src_link(FALLBACK_URL, FALLBACK_LABEL)])
    body.append(
        '<section><div class="section-head"><h2>Every register on the site, and where it lives</h2>'
        '<p class="muted">Ten registers: eight machine-readable tables and two prose annexes</p></div>'
        + table(rtrs, rhdr, cls="grid",
                caption="The review surface as it stands: which page holds which register, "
                        "how many rows it has and which session wrote it.")
        + "</section>")

    # ---- canonical decisions ----------------------------------------------
    chdr = ["#", "Decision", "What we know", "What is missing", "Options",
            "Recommendation", "Blocks", "Source rows", "Official reference"]
    ctrs = []
    for d in sorted(decisions, key=lambda r: int(r["order"])):
        srcs = by_dec.get(d["id"], [])
        chips = " ".join(
            f'<a class="pill" href="{e(m["register_page"])}" title="{e(m["register_label"])}">'
            f'{e(m["row_id"])}</a>' for m in sorted(srcs, key=lambda m: m["row_id"]))
        tone = "pos" if d["status"].startswith(("Decided", "Running", "In progress")) else ""
        ctrs.append([
            f'<strong>{e(d["order"])}</strong>',
            f'<strong>{e(d["decision"])}</strong><br><span class="muted">{e(d["area"])}</span>'
            f'<br>{pill(d["status"], tone)}<br><code>{e(d["id"])}</code>',
            e(d["what_we_know"]),
            e(d["what_is_missing"]),
            e(d["options"]),
            e(d["recommendation"]),
            e(d["blocks"]),
            chips,
            ref(d["official_reference"]),
        ])
    body.append(
        '<section><div class="section-head"><h2>The sixteen decisions</h2>'
        '<p class="muted">Ordered: the ones that unblock the most come first</p></div>'
        '<div class="table-tools"><input class="filter" type="search" '
        'placeholder="Filter decisions, options, blockers…"></div>'
        + table(ctrs, chdr, cls="grid",
                caption="Canonical decisions consolidated from all ten registers, with the "
                        "original row ids that produced each one.")
        + "</section>")

    # ---- recommended path -------------------------------------------------
    body.append(
        '<section><div class="section-head"><h2>Recommended path</h2>'
        '<p class="muted">A suggested order; nothing is implemented until you choose</p></div>'
        '<div class="findings"><ol>'
        '<li><strong>First — DH-02 (price provenance) and DH-04 (data freshness).</strong> '
        'Every other number on the site is conditional on these two. Without executable '
        'prices, no ROI can be validated; without a fresh pin, the board is describing a '
        'season that has already moved on.</li>'
        '<li><strong>Second — DH-01 (evidence display).</strong> A one-line policy change '
        'that decides whether the leaderboard can be read at all. It is reversible and costs '
        'nothing.</li>'
        '<li><strong>Third — DH-05, DH-06 and DH-07 (availability).</strong> Now that the '
        'deficiency join runs on every capture, this is no longer blocked on data collection; '
        'it is blocked on the decision to price it. Do not add it to the model without the '
        'availability gate (DH-05 option B).</li>'
        '<li><strong>Fourth — DH-03 (prospective proof).</strong> It is already running and '
        'already hash-chained. It needs weeks, not code.</li>'
        '<li><strong>Last — DH-10 and DH-11 (reward and staking).</strong> These are yours '
        'alone: the repository cannot answer them, and no reward should be defined before '
        'DH-02 and DH-03 produce evidence.</li>'
        '<li><strong>Never — DH-15 option B.</strong> Relaxing a gate to let a strategy '
        'through produces a winner, not evidence. The build keeps all eight gates '
        'fail-closed and asks you to confirm that.</li>'
        '</ol></div></section>')

    # ---- first prospective result -----------------------------------------
    fsum = json.loads((RV / "forward_summary.json").read_text()) if (RV / "forward_summary.json").exists() else {}
    if fsum:
        fgraded = read(RV / "forward_graded_2026_11_13.csv")
        fo = fsum["official"][0]
        fh = ["Pick", "Strategy", "Market", "Side", "Line", "Price", "Frozen (UTC)",
              "Official final", "Outcome", "Units", "Settled against"]
        ftrs = []
        for g in fgraded:
            tone = {"win": "pos", "loss": "neg", "push": ""}.get(g["outcome"], "")
            ftrs.append([
                f'<code>{e(g["pick_id"])}</code>', e(g["strategy"]), e(g["market"]),
                e(g["sides"].strip("[]")), e(g["lines"].strip("[]")),
                e(g["prices"].strip("[]")), e(g["frozen_utc"]),
                f'{e(fo["away_team"])} {e(fo["away_score"])} – '
                f'{e(fo["home_team"])} {e(fo["home_score"])} ({e(fo["status_on_page"])})',
                pill(g["outcome"], tone),
                f'{float(g["pnl_units"]):+.4f}',
                src_link(g["settled_against"].split(",")[0].strip(), "official game page"),
            ])
        body.append(
            '<section><div class="section-head"><h2>Evidence for DH-03 — the first '
            'prospective result</h2>'
            '<p class="muted">Frozen before kickoff, graded only against an official '
            'final</p></div>'
            f'<p>One Week 10 game has settled. Its selections were frozen at '
            f'<code>{e(fsum["freeze"]["frozen_utc"])}</code> and pushed to GitHub at '
            f'<code>{e(fsum["freeze"]["pushed_utc"])}</code> — '
            f'{e(fsum["freeze"]["lead_time"])}. The final was then read from '
            f'{src_link(fo["source_url"], "the official game page")} and cross-checked on '
            f'{src_link(fo["corroborating_url"], "the official scoreboard")}. '
            f'<strong>{fsum["picks_settled"]} of {fsum["picks_total"]} frozen picks are now '
            f'decided: {fsum["wins"]} win, {fsum["losses"]} loss, {fsum["pushes"]} push, '
            f'{fsum["net_units"]:+.4f} units at flat stakes.</strong> '
            f'{fsum["picks_still_open"]} picks remain open.</p>'
            + flag(f'<strong>This is not a result.</strong> {e(fsum["verdict"])}. Four picks '
                   f'on one game cannot distinguish skill from luck, and the ledger is graded '
                   f'without executable prices, so the unit figures are research accounting, '
                   f'not money. What it does show is that the mechanism works end to end: '
                   f'freeze, push, official settlement, grade.', "warn")
            + table(ftrs, fh, cls="grid",
                    caption="Forward-ledger picks settled against the official NFL final; "
                            "flat one-unit stake, no commission, no limits.")
            + "</section>")

    # ---- cross reference --------------------------------------------------
    xhdr = ["Decision", "Register", "Row", "Published on", "Official reference"]
    ref_by = {d["id"]: d["official_reference"] for d in decisions}
    xtrs = [[
        f'<code>{e(m["canonical_id"])}</code>',
        e(m["register_label"]),
        f'<a href="{e(m["register_page"])}"><code>{e(m["row_id"])}</code></a>',
        f'<a href="{e(m["register_page"])}">{e(m["register_page"])}</a>',
        ref(ref_by.get(m["canonical_id"], "")),
    ] for m in sorted(mapping, key=lambda m: (m["canonical_id"], m["register"], m["row_id"]))]
    body.append(
        '<section><div class="section-head"><h2>Cross-reference: every register row</h2>'
        f'<p class="muted">{len(mapping)} rows · each register row appears exactly once</p></div>'
        '<p>This is the audit trail. If you disagree with a grouping, this table tells you '
        'which original row to go back to.</p>'
        '<div class="table-tools"><input class="filter" type="search" '
        'placeholder="Filter by id, register or page…"></div>'
        + table(xtrs, xhdr, cls="grid",
                caption="Every row of every machine-readable register, mapped to one "
                        "canonical decision.")
        + "</section>")

    # ---- coverage proof ---------------------------------------------------
    vhdr = ["Register", "File", "Rows", "Mapped", "Unmapped", "Ids missing",
            "Reference most cited by its rows"]
    vtrs = [[e(c["label"]), f'<code>{e(c["file"])}</code>', e(c["rows"]), e(c["mapped"]),
             e(c["unmapped"]), dash(c["unmapped_ids"]),
             src_link(c["reference_url"], c["reference_label"])] for c in coverage]
    body.append(
        '<section><div class="section-head"><h2>Coverage proof</h2>'
        '<p class="muted">Generated by <code>pipeline/build_hub.py</code>, which fails the '
        'build on an unmapped row, a double-mapped row or an id that does not exist</p></div>'
        + table(vtrs, vhdr, cls="grid",
                caption="Every register row is claimed by exactly one canonical decision.")
        + "</section>")

    # ---- how to decide ----------------------------------------------------
    body.append(
        '<section><div class="section-head"><h2>How a decision gets recorded</h2></div>'
        '<div class="findings"><ol>'
        '<li>Choose an option for one or more <code>DH-</code> rows on this page.</li>'
        '<li>Record it in <a href="https://github.com/karagemop466-tech/Korea1/blob/main/'
        'DECISIONS.md">DECISIONS.md</a> with the date and the <code>DH-</code> id.</li>'
        '<li>Only then is the change implemented, in a pull request that names the decision '
        'it carries out.</li>'
        '<li>Nothing in this repository implements a decision on your behalf. The pages '
        'below are options and evidence, not actions taken.</li>'
        '</ol></div></section>')

    return "\n".join(body)


def main() -> int:
    title = "Decision hub"
    subtitle = ("Six suggestion registers and five question registers reduced to sixteen "
                "decisions, with all 166 source rows mapped and nothing implemented until "
                "you choose.")
    html = layout("decision-hub.html", title, subtitle, build(), wide=True)
    path = ROOT / "decision-hub.html"
    path.write_text(html, encoding="utf-8")
    print(f"  wrote {path.name} ({len(html):,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
