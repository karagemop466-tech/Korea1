"""R7-09a — the suggestions hub: one place to review proposals and choose a path
before anything is implemented.

Why a new page instead of editing an existing one
-------------------------------------------------
Four earlier sessions already wrote four suggestion registers (76 rows) and four
question registers (74 + 90 rows across two independent merges). Those pages stay
exactly as their owners wrote them. What was missing is a single **decision
surface**: a page where each proposal is a row, each row carries the evidence it
needs, and the reader is asked to pick one of a small number of labelled paths.

This module implements that surface for the proposals generated by *this* session
— the eight requirements handed over plus the integration work — because a
proposal whose evidence is a measurement made today cannot be judged from a
register written yesterday. Every proposal references the page where its evidence
lives, and every one states what it costs, what it changes, and what would make
it wrong.

Design rules
------------
* A proposal is never published without (a) the evidence that motivates it,
  (b) an explicit cost, and (c) a reversal condition.
* "Recommended" is a separate column from "status", so a recommendation cannot be
  mistaken for an approval. Nothing on this page has been implemented beyond the
  measurement it describes.
* The path labels are deliberately stable: **A** (publish and stop), **B** (spend
  on data), **C** (spend on modelling), **D** (change the product). A reviewer
  chooses a letter; the consequences of each letter are printed.

Outputs
-------
data/integration/suggestions_2026_11_14.csv
suggestions-hub.html

Run:  python pipeline/render_suggestions_hub.py
"""
