def main() -> None:
    df = build()
    (ROOT / "suggestions-hub.html").write_text(
        layout("suggestions-hub.html", "Suggestions hub",
               "Review the proposals and choose a path before a single change is implemented.",
               body(df), wide=True))
    write_json(INT / "suggestions_2026_11_14_summary.json",
               {"proposals": int(len(df)),
                "by_path": df.suggested_path.value_counts().to_dict(),
                "implemented": 0,
                "note": "Every proposal is a proposal. The measurement behind it is done; the change is not."})
    print(f"wrote suggestions-hub.html · {len(df)} proposals · "
          f"{df.suggested_path.value_counts().to_dict()}")


if __name__ == "__main__":
    main()
